/* sitefoot.js — pied de page commun à TOUTES les pages du sous-domaine market.
   Source unique (décision Elena, 2026-06-13) — pendant du siteheader.js.

   Footer public à 3 colonnes (convention product-set-up révisée par Elena le 2026-09-23,
   appliquée ici au product wrap-up du 2026-09-24) :
     1. la marque : nom, phrase de présentation, sélecteur de langue ;
     2. « Projet » : accueil, méthode, marchés suivis ;
     3. « Corporate » : à propos, pricing, conditions générales, mentions légales.
   Puis la ligne « © année Nom — domaine ».
   ⚠ AUCUN lien d'administration ici : Préférences, documentation technique, GitHub et
   Data analytics vivent dans l'Admin Footer du gate central, visible d'Elena seule.

   Bilingue (décision Elena, 2026-06-15) : FR = URLs actuelles, EN = préfixe /en/.
   La langue est déduite de l'URL. Les liens internes sont construits relativement
   à la racine de langue (L) ; tant qu'une page n'a pas de version EN, son lien
   retombe sur le FR (EN_AVAILABLE ci-dessous).
*/
(function () {
  "use strict";

  /* ═══════════════════════════════════════════════════════════════════════════
     CONFIGURATION DU SITE — SOURCE DE VÉRITÉ UNIQUE
     Marque, pied de page, liste des pages et des marchés : tout se règle ICI.
     Les 40 pages du site (dont les 20 runs figés) chargent déjà ce fichier :
     ajouter un marché ou une page ne demande d'en rouvrir aucune.
     ═══════════════════════════════════════════════════════════════════════════ */
  var CONFIG = {
    brand: "My Market Data",
    domain: "market.shoette.com",

    // Phrase de présentation (colonne 1).
    tagline: {
      fr: "Études de marché générées par un agent IA : acteurs, parts de marché, " +
          "positionnement interactif et recommandations stratégiques — un rapport daté à chaque cycle.",
      en: "Market studies generated by an AI agent: players identified, shares estimated, " +
          "interactive positioning and strategic recommendations — a dated report each cycle."
    },

    // Colonne 2 « Projet » : accueil, méthode, puis les marchés suivis.
    // AJOUTER UN MARCHÉ = une ligne dans chaque langue (+ son entrée dans EN_AVAILABLE si traduit).
    projet: {
      fr: [
        ["", "Accueil"],
        ["how-it-works/", "Comment ça marche"],
        ["how-it-works/focus-step-1/", "Focus sur l'étape 1"],
        ["how-it-works/focus-step-2/", "Focus sur l'étape 2"],
        ["how-it-works/focus-step-3/", "Focus sur l'étape 3"],
        ["how-it-works/focus-step-4/", "Focus sur l'étape 4"],
        ["apps-perte-de-poids/", "Applications mobiles d'assistance à la perte de poids"],
        ["greeting-cards-us/", "Cartes de vœux & d'expression sociale — États-Unis"],
        ["micro-seed/", "Capital d'amorçage à micro-tickets — business angels & micro-fonds"],
        ["perso-ecommerce/", "Outils SaaS de personnalisation e-commerce"]
      ],
      en: [
        ["", "Home"],
        ["how-it-works/", "How it works"],
        ["how-it-works/focus-step-1/", "Focus on Step 1"],
        ["how-it-works/focus-step-2/", "Focus on Step 2"],
        ["how-it-works/focus-step-3/", "Focus on Step 3"],
        ["how-it-works/focus-step-4/", "Focus on Step 4"],
        ["apps-perte-de-poids/", "Mobile weight-loss assistance apps"],
        ["greeting-cards-us/", "Greeting & social cards — United States"],
        ["micro-seed/", "Micro-ticket seed capital — angels & micro-funds"],
        ["perso-ecommerce/", "E-commerce personalization SaaS tools"]
      ]
    },

    // Colonne 3 « Corporate » — n'y mettre une entrée que si la page existe.
    // (« Fonctionnalités » et « Démo » n'existent pas sur ce site : elles sont absentes.)
    corporate: {
      fr: [
        ["a-propos.html", "À propos"],
        ["pricing.html", "Pricing"],
        ["conditions-generales.html", "Conditions générales"],
        ["mentions-legales.html", "Mentions légales"]
      ],
      en: [
        ["a-propos.html", "About"],
        ["pricing.html", "Pricing"],
        ["conditions-generales.html", "Terms and conditions"],
        ["mentions-legales.html", "Legal notice"]
      ]
    },

    // Libellés de structure.
    labels: {
      fr: { projet: "Projet", corporate: "Corporate",
            disclaimer: "Études générées par IA, données estimées fournies à titre indicatif.",
            host: "Hébergé par OVH" },
      en: { projet: "Project", corporate: "Corporate",
            disclaimer: "Studies generated by AI; estimated figures, for information only.",
            host: "Hosted by OVH" }
    },

    // Pages disposant déjà d'une version EN (chemins relatifs à la racine de langue).
    // Tant qu'un chemin n'y est pas, son lien pointe vers le FR même en page EN.
    EN_AVAILABLE: {
      "": 1, "apps-perte-de-poids/": 1, "how-it-works/": 1,
      "how-it-works/focus-step-1/": 1, "how-it-works/focus-step-2/": 1,
      "how-it-works/focus-step-3/": 1, "how-it-works/focus-step-4/": 1,
      "how-it-works/focus-step-1/process-skill-11juin2026/": 1,
      "apps-perte-de-poids/s1-1_2026-06-11/": 1, "apps-perte-de-poids/s1-2_2026-06-11/": 1,
      "apps-perte-de-poids/s2-1_2026-06-11/": 1, "apps-perte-de-poids/s3-1_2026-06-12/": 1,
      "apps-perte-de-poids/s3-2_2026-06-16/": 1, "apps-perte-de-poids/s4-1_2026-06-12/": 1,
      "perso-ecommerce/": 1, "perso-ecommerce/s1-1_2026-07-29/": 1,
      "a-propos.html": 1, "pricing.html": 1,
      "conditions-generales.html": 1, "mentions-legales.html": 1,
      "preferences.html": 1
    },

    // Pages servies en ANGLAIS PAR DÉFAUT (décision Elena, 2026-09-06 — provisoire) :
    // une redirection 302 côté serveur (.htaccess) envoie l'URL FR vers /en/.
    // Le sélecteur de langue y porte un paramètre explicite : « ?lang=fr » échappe la
    // redirection (et mémorise le choix en cookie, cf. siteheader.js), « ?lang=en »
    // revient au défaut anglais. Pour rendre une page au français par défaut : retirer
    // son chemin ci-dessous ET sa règle dans le .htaccess.
    DEFAULT_EN: { "": 1, "perso-ecommerce/": 1 }
  };
  /* ═════════════════════════ fin de la configuration ═══════════════════════ */

  var self = document.currentScript;
  var src = (self && self.getAttribute("src")) || "";
  var base = src.replace(/assets\/sitefoot\.js(?:[?#].*)?$/, "") || "./";

  // Langue (FR par défaut, EN sous /en/) + racine de langue relative.
  var path = location.pathname.replace(/\/[^/]*\.html$/, "/");
  var EN = /(^|\/)en(\/|$)/.test(path);
  var L = base + (EN ? "en/" : "");
  var LANG = EN ? "en" : "fr";
  var T = CONFIG.labels[LANG];

  function href(p) { return (EN && CONFIG.EN_AVAILABLE[p]) ? (L + p) : (base + p); }

  var STYLE_ID = "sitefoot-style";
  var CSS =
    ".sitefoot{margin-top:80px;background:#f4f1ea;border-top:1px solid #e7e2d8;" +
      "color:#494d59;font-family:'Hanken Grotesk',system-ui,-apple-system,'Segoe UI',sans-serif;" +
      "font-size:13.5px;line-height:1.5;}" +
    ".sitefoot-inner{max-width:calc(50vw + 550px);margin:0 auto;padding:40px 20px 28px;}" +
    ".sitefoot-top{display:flex;flex-wrap:wrap;gap:26px 48px;align-items:flex-start;}" +
    ".sitefoot-about{flex:1 1 260px;min-width:230px;}" +
    ".sitefoot-brand{font-family:'Hanken Grotesk','Plus Jakarta Sans',system-ui,sans-serif;font-weight:800;" +
      "font-size:18px;letter-spacing:-.015em;color:#1a1c22;text-decoration:none;}" +
    ".sitefoot-brand .dot{color:#f4684f;}" +
    ".sitefoot-about p{margin:11px 0 0;max-width:40ch;color:#494d59;font-size:14px;}" +
    ".sitefoot-group{flex:0 0 auto;max-width:34ch;}" +
    ".sitefoot-h{display:block;font-family:'IBM Plex Mono',ui-monospace,monospace;font-size:11px;font-weight:600;" +
      "text-transform:uppercase;letter-spacing:.12em;color:#868a93;margin:0 0 13px;}" +
    ".sitefoot-group ul{list-style:none;margin:0;padding:0;}" +
    ".sitefoot-group li{margin:0 0 8px;}" +
    ".sitefoot-group a{color:#494d59;text-decoration:none;font-weight:500;font-size:14px;}" +
    ".sitefoot-group a:hover{color:#1a1c22;}" +
    ".sitefoot-legal{margin-top:28px;padding-top:18px;border-top:1px solid #e7e2d8;" +
      "display:flex;flex-wrap:wrap;justify-content:space-between;align-items:baseline;gap:10px 24px;" +
      "font-family:'IBM Plex Mono',ui-monospace,monospace;font-size:12px;color:#868a93;}" +
    ".sitefoot-legal a{color:#868a93;text-decoration:none;}" +
    ".sitefoot-legal a:hover{color:#1a1c22;}" +
    ".sitefoot-legal__txt{display:flex;flex-wrap:wrap;gap:4px 18px;}" +
    ".sitefoot-lang{display:inline-flex;align-items:baseline;gap:8px;white-space:nowrap;" +
      "margin-top:16px;font-family:'IBM Plex Mono',ui-monospace,monospace;font-size:12px;color:#868a93;}" +
    ".sitefoot-lang a{color:#868a93;text-decoration:none;}" +
    ".sitefoot-lang a:hover{color:#1a1c22;}" +
    ".sitefoot-lang .is-active{color:#1a1c22;font-weight:700;}" +
    ".sitefoot-lang .is-soon{opacity:.4;cursor:default;}" +
    ".sitefoot-lang .sep{opacity:.5;}" +
    "@media print{.sitefoot{display:none!important;}}" +
    "@media (max-width:560px){.sitefoot-inner{padding:30px 18px 24px;}" +
      ".sitefoot-top{gap:22px 32px;}.sitefoot-legal{flex-direction:column;}}";

  function injectStyle() {
    if (document.getElementById(STYLE_ID)) return;
    var s = document.createElement("style");
    s.id = STYLE_ID; s.textContent = CSS;
    (document.head || document.documentElement).appendChild(s);
  }

  function linkList(items) {
    var ul = document.createElement("ul");
    items.forEach(function (it) {
      var li = document.createElement("li");
      var a = document.createElement("a");
      a.href = href(it[0]);
      a.textContent = it[1];
      li.appendChild(a); ul.appendChild(li);
    });
    return ul;
  }

  function group(label, items) {
    if (!items || !items.length) return null;      // une colonne vide se masque d'elle-même
    var nav = document.createElement("nav");
    nav.className = "sitefoot-group";
    nav.setAttribute("aria-label", label);
    var h = document.createElement("span");
    h.className = "sitefoot-h"; h.textContent = label;
    nav.appendChild(h); nav.appendChild(linkList(items));
    return nav;
  }

  // Sélecteur FR/EN : même page dans l'autre langue (URL absolue, structure de prod /en/).
  function langSwitch() {
    var box = document.createElement("div");
    box.className = "sitefoot-lang";
    var siteRoot = new URL(base, location.href).pathname;     // racine du site, absolue (/, /site/, …)
    var pn = location.pathname.replace(/index\.html$/, "");
    var langRoot = siteRoot + (EN ? "en/" : "");
    var sub = pn.indexOf(langRoot) === 0 ? pn.slice(langRoot.length) : "";
    var enOk = EN || CONFIG.EN_AVAILABLE[sub] === 1;           // version EN dispo pour cette page ?
    var dflEn = CONFIG.DEFAULT_EN[sub] === 1;                  // page servie en anglais par défaut ?
    var items = [
      { label: "FR", url: siteRoot + sub + (dflEn ? "?lang=fr" : ""), active: !EN, soon: false },
      { label: "EN", url: siteRoot + "en/" + sub + (dflEn ? "?lang=en" : ""), active: EN, soon: !EN && !enOk }
    ];
    items.forEach(function (it, i) {
      if (i) { var s = document.createElement("span"); s.className = "sep"; s.textContent = "·"; box.appendChild(s); }
      var el;
      if (it.active) { el = document.createElement("span"); el.className = "is-active"; }
      else if (it.soon) { el = document.createElement("span"); el.className = "is-soon"; el.title = "English version coming soon"; }
      else { el = document.createElement("a"); el.href = it.url; }
      el.textContent = it.label;
      el.setAttribute("hreflang", it.label.toLowerCase());
      box.appendChild(el);
    });
    return box;
  }

  function build() {
    var foot = document.createElement("footer");
    foot.className = "sitefoot"; foot.setAttribute("role", "contentinfo");
    var inner = document.createElement("div"); inner.className = "sitefoot-inner";

    var top = document.createElement("div"); top.className = "sitefoot-top";

    // Colonne 1 — la marque, sa phrase de présentation, le sélecteur de langue.
    var about = document.createElement("div"); about.className = "sitefoot-about";
    var brand = document.createElement("a"); brand.className = "sitefoot-brand"; brand.href = L;
    brand.appendChild(document.createTextNode(CONFIG.brand));
    var dot = document.createElement("span"); dot.className = "dot"; dot.textContent = "."; brand.appendChild(dot);
    about.appendChild(brand);
    var p = document.createElement("p"); p.textContent = CONFIG.tagline[LANG]; about.appendChild(p);
    about.appendChild(langSwitch());
    top.appendChild(about);

    // Colonnes 2 et 3.
    [group(T.projet, CONFIG.projet[LANG]), group(T.corporate, CONFIG.corporate[LANG])]
      .forEach(function (g) { if (g) top.appendChild(g); });

    inner.appendChild(top);

    // Bas de footer — « © année Nom — domaine ».
    var legal = document.createElement("div"); legal.className = "sitefoot-legal";
    var txt = document.createElement("div"); txt.className = "sitefoot-legal__txt";
    var l1 = document.createElement("span");
    l1.appendChild(document.createTextNode("© " + new Date().getFullYear() + " " + CONFIG.brand + " — "));
    var dom = document.createElement("a"); dom.href = L; dom.textContent = CONFIG.domain;
    l1.appendChild(dom);
    var l2 = document.createElement("span"); l2.textContent = T.disclaimer;
    var l3 = document.createElement("span"); l3.textContent = T.host;
    txt.appendChild(l1); txt.appendChild(l2); txt.appendChild(l3);
    legal.appendChild(txt);
    inner.appendChild(legal);

    foot.appendChild(inner);
    return foot;
  }

  function inject() {
    if (document.querySelector(".sitefoot")) return;
    injectStyle();
    document.body.appendChild(build());
  }

  if (document.body) { inject(); } else { document.addEventListener("DOMContentLoaded", inject); }
})();
